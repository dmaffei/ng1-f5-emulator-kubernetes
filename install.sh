#!/bin/bash
# install.sh — ng1-f5-emulator-kubernetes
# Deploys the tmos-shim-kubernetes container that translates Kubernetes
# LoadBalancer Services and Ingress rules into F5 BIG-IP iControl REST
# objects for nGeniusONE BIG-IP Discovery.
#
# Usage:
#   bash install.sh
#
# Pre-requisites: see INSTALL.md

set -euo pipefail

BOLD="\033[1m"
GREEN="\033[32m"
YELLOW="\033[33m"
RED="\033[31m"
RESET="\033[0m"

info()    { echo -e "${GREEN}[INFO]${RESET}  $*"; }
warn()    { echo -e "${YELLOW}[WARN]${RESET}  $*"; }
error()   { echo -e "${RED}[ERROR]${RESET} $*"; exit 1; }
section() { echo -e "\n${BOLD}── $* ──${RESET}"; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# ── Banner ────────────────────────────────────────────────────────────────────
echo -e "${BOLD}"
echo "  ng1-f5-emulator-kubernetes — Install"
echo "  Kubernetes → F5 BIG-IP emulator for nGeniusONE BIG-IP Discovery"
echo -e "${RESET}"

# ── Check dependencies ────────────────────────────────────────────────────────
section "Checking dependencies"

command -v docker   >/dev/null 2>&1 || error "docker is not installed"
command -v openssl  >/dev/null 2>&1 || error "openssl is not installed"
docker compose version >/dev/null 2>&1 || error "docker compose (v2) is not installed"
info "docker: $(docker --version)"
info "docker compose: $(docker compose version)"

# ── Collect configuration ─────────────────────────────────────────────────────
section "Configuration"

# K8s API server
read -rp "  Kubernetes API server URL [https://10.0.0.110:8443]: " K8S_API
K8S_API="${K8S_API:-https://10.0.0.110:8443}"

# Service account token
read -rp "  Path to service account token file [kubeconfig/token]: " TOKEN_FILE
TOKEN_FILE="${TOKEN_FILE:-kubeconfig/token}"
[[ -f "$TOKEN_FILE" ]] || error "Token file not found: $TOKEN_FILE — see INSTALL.md Step 2"

# CA cert
read -rp "  Path to cluster CA cert [kubeconfig/ca.crt]: " CA_FILE
CA_FILE="${CA_FILE:-kubeconfig/ca.crt}"
[[ -f "$CA_FILE" ]] || warn "CA cert not found: $CA_FILE — SSL verification will be disabled"
VERIFY_SSL="true"
[[ -f "$CA_FILE" ]] || VERIFY_SSL="false"

# Host IP (where container will bind)
read -rp "  Host IP for port binding [192.168.30.35]: " HOST_IP
HOST_IP="${HOST_IP:-192.168.30.35}"

# Port
read -rp "  Port to expose tmos-shim on [8447]: " PORT
PORT="${PORT:-8447}"

# nG1
read -rp "  nGeniusONE URL (for auto-relearn) [https://192.168.30.20:443]: " NG1_URL
NG1_URL="${NG1_URL:-https://192.168.30.20:443}"

read -rp "  nG1 username [admin]: " NG1_USER
NG1_USER="${NG1_USER:-admin}"

read -rsp "  nG1 password [netscout1]: " NG1_PASS
NG1_PASS="${NG1_PASS:-netscout1}"
echo

read -rp "  BIG-IP device name in nG1 [kubernetes]: " NG1_LB_NAME
NG1_LB_NAME="${NG1_LB_NAME:-kubernetes}"

# Namespaces
read -rp "  Namespaces to monitor (comma-separated, blank = all) []: " NAMESPACES

# Include ClusterIP
read -rp "  Include ClusterIP services? [n]: " INCLUDE_CIP
INCLUDE_CIP_BOOL="false"
[[ "$INCLUDE_CIP" =~ ^[yY] ]] && INCLUDE_CIP_BOOL="true"

# tmos-shim credentials (nG1 uses these to authenticate to the shim)
read -rp "  tmos-shim username (nG1 BIG-IP Discovery) [admin]: " SHIM_USER
SHIM_USER="${SHIM_USER:-admin}"

read -rsp "  tmos-shim password (nG1 BIG-IP Discovery) [netscout1]: " SHIM_PASS
SHIM_PASS="${SHIM_PASS:-netscout1}"
echo

# ── Generate self-signed TLS cert for shim ────────────────────────────────────
section "TLS certificate"

mkdir -p certs
if [[ -f certs/cert.pem && -f certs/key.pem ]]; then
    info "Existing certs found — skipping generation"
else
    info "Generating self-signed certificate..."
    openssl req -x509 -newkey rsa:2048 -nodes \
        -keyout certs/key.pem \
        -out certs/cert.pem \
        -days 3650 \
        -subj "/CN=tmos-shim-kubernetes/O=NETSCOUT" \
        -addext "subjectAltName=IP:${HOST_IP}" \
        >/dev/null 2>&1
    info "Certificate generated (valid 10 years)"
fi

# ── Write backends/kubernetes.yml ─────────────────────────────────────────────
section "Writing backend config"

TOKEN=$(cat "$TOKEN_FILE")
mkdir -p backends

cat > backends/kubernetes.yml << YAML
# kubernetes backend — auto-generated by install.sh
kubernetes:
  type: kubernetes
  api_url: ${K8S_API}
  token: "${TOKEN}"
  ca_cert: /app/kubeconfig/ca.crt
  verify_ssl: ${VERIFY_SSL}
  ng1_url: ${NG1_URL}
  ng1_lb_name: ${NG1_LB_NAME}
  ng1_user: ${NG1_USER}
  ng1_pass: ${NG1_PASS}
  include_clusterip: ${INCLUDE_CIP_BOOL}
  namespaces: "${NAMESPACES}"
YAML

info "backends/kubernetes.yml written"

# ── Write .env ────────────────────────────────────────────────────────────────
cat > .env << ENV
TMOS_USERNAME=${SHIM_USER}
TMOS_PASSWORD=${SHIM_PASS}
TLS_CERT=certs/cert.pem
TLS_KEY=certs/key.pem
PORT=8443
TMOS_HOST_IP=${HOST_IP}
BACKENDS_FILE=/app/backends.yml
ENV

info ".env written"

# ── Update docker-compose.yml port binding ────────────────────────────────────
sed -i "s|\".*:8447:8443\"|\"${HOST_IP}:${PORT}:8443\"|g" docker-compose.yml
info "docker-compose.yml port set to ${HOST_IP}:${PORT}"

# ── Copy kubeconfig ───────────────────────────────────────────────────────────
section "Kubeconfig"

mkdir -p kubeconfig
[[ -f "$TOKEN_FILE" ]] && cp "$TOKEN_FILE" kubeconfig/token
[[ -f "$CA_FILE" ]]    && cp "$CA_FILE"    kubeconfig/ca.crt

info "kubeconfig/ populated"

# ── Register in nG1 BIG-IP Discovery ─────────────────────────────────────────
section "nG1 BIG-IP Discovery registration"

info "Checking if device already registered in nG1..."
HTTP_CODE=$(curl -sk -o /dev/null -w "%{http_code}" \
    -u "${NG1_USER}:${NG1_PASS}" \
    "${NG1_URL}/ng1api/ncm/bigip/loadbalancers/${NG1_LB_NAME}" 2>/dev/null || echo "000")

if [[ "$HTTP_CODE" == "200" ]]; then
    info "Device '${NG1_LB_NAME}' already registered in nG1 — skipping"
else
    info "Registering device '${NG1_LB_NAME}' in nG1..."
    RESULT=$(curl -sk -X POST \
        -u "${NG1_USER}:${NG1_PASS}" \
        -H "Content-Type: application/json" \
        "${NG1_URL}/ng1api/ncm/bigip/loadbalancers" \
        -d "{\"LoadBalancers\":[{\"Host\":\"${HOST_IP}\",\"LoginProviderName\":\"tmos\",\"Name\":\"${NG1_LB_NAME}\",\"Password\":\"${SHIM_PASS}\",\"Port\":${PORT},\"Username\":\"${SHIM_USER}\"}]}" \
        2>/dev/null | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('message','?'))" 2>/dev/null || echo "API call failed")
    info "nG1 registration: $RESULT"
fi

# ── Build and start ───────────────────────────────────────────────────────────
section "Building and starting container"

docker compose down 2>/dev/null || true
docker compose build --no-cache
docker compose up -d

info "Waiting for container to start..."
sleep 15

HEALTH=$(curl -sk --max-time 5 "https://${HOST_IP}:${PORT}/health" 2>/dev/null | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('status','?'))" 2>/dev/null || echo "unreachable")

if [[ "$HEALTH" == "ok" ]]; then
    info "Container healthy ✓"
else
    warn "Health check returned: ${HEALTH} — check 'docker logs tmos-shim-kubernetes'"
fi

# ── Trigger initial nG1 relearn ───────────────────────────────────────────────
section "Triggering nG1 relearn"

RELEARN=$(curl -sk -X POST \
    -u "${NG1_USER}:${NG1_PASS}" \
    -H "Content-Type: application/json" \
    "${NG1_URL}/ng1api/ncm/bigip/loadbalancers/${NG1_LB_NAME}/rediscoverLBDevice" \
    -d '{}' 2>/dev/null | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('message','?'))" 2>/dev/null || echo "skipped")
info "nG1 relearn: $RELEARN"

# ── Summary ───────────────────────────────────────────────────────────────────
section "Installation complete"

VIRTUALS=$(curl -sk -u "${SHIM_USER}:${SHIM_PASS}" "https://${HOST_IP}:${PORT}/mgmt/tm/ltm/virtual" 2>/dev/null | \
    python3 -c "import sys,json; d=json.load(sys.stdin); print(len(d.get('items',[])))" 2>/dev/null || echo "?")

echo ""
echo -e "  ${BOLD}Container:${RESET}  tmos-shim-kubernetes"
echo -e "  ${BOLD}Endpoint:${RESET}   https://${HOST_IP}:${PORT}"
echo -e "  ${BOLD}Health:${RESET}     https://${HOST_IP}:${PORT}/health"
echo -e "  ${BOLD}VIPs found:${RESET} ${VIRTUALS}"
echo -e "  ${BOLD}nG1 device:${RESET} ${NG1_LB_NAME}"
echo ""
echo -e "  ${BOLD}nG1 BIG-IP Discovery:${RESET}"
echo -e "    Host: ${HOST_IP}  Port: ${PORT}"
echo -e "    Username: ${SHIM_USER}  Password: ${SHIM_PASS}"
echo ""
info "Go to nG1 → Application Configuration → BIG-IP Discovery to review and Apply entries"
echo ""
